<h3>The School Campus</h3>
<p><b>ACACIA</b> is located at Vikuruti village, Mlandizi Township, Kibaha District in Coast Region. It is about 71km from Dar es Salaam and 51/2 km from Mlandizi town, along Mlandizi-Bagamoyo road.
The school campus covers an area of 55 acres and planned to accommodate kindergarten, primary school, secondary school and a vocational training centre with all the necessary facilities – classrooms, dormitories, laborato
houses, libraries, playgrounds for games and sports.</p>


<p>
<b>This area was chosen by the owners of the school due to the following advantages.</b>
The school campus is non-noise, unpolluted from industries and vehicles. It offers the best environment for learning.

The campus retains its natural form, acacias, green bushes, grass and tranquility. Fruit and decoration trees have been planted.

The campus is easily accessible by the public means of transport (the daladalas) that ply between Mlandizi and Bagamoyo; every after 30 minutes.
</p>

<h3>Teaching Staff</h3>
<p>Acacia has enough teaching staff that meets all students academic requirements
. the teachers are both diploma holders and graduates from various local and international 
Universities. They are commited to their profession</p>

<h3>Accomodation</h3>
<p>
Acacia Secondary School accommodates about both boys and girls; it has several boys’ dormitories that accommodate at least 30 boys in each dormitory and 80 girls that can accommodate 4 girls in each room.
</p>

<h3>The Library</h3>
<p>
The two well stocked libraries have an extensive range of books, materials and resources. The library features reading corners, study areas, 
spaces for groups of students and PC workstations which are readily available for children to access information on-line or from CDs and DVDs.
</p>

<h3>Sports and Games</h3>
<p>Young children are uniquely vulnerable to distractions. To avoid this students at ACACIA
are frequently exposed to both indoor and field sports and games. The school offers football,
volleyball, drama, debates, quizzes and the like. All these are meant to identify talents and be a great stimulant for the students'
minds as they persue their studies.</p>

<h3>Transportation</h3>
<p>
The School has a mini buses to cater for School and Teachers to town and other places</p>


