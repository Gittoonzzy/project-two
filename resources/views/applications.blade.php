Admissions to Acacia School can be made at any time through the Registrar, although there are cut-off dates during the year, which are designated by the Ministry of Education. The Ministry also requires all students to submit certain documents to the school before they can enter the educational system in Tanzania.
<br/>
<br/>
<b>These are:</b>
<ol>
<li> 2 copies of your child’s passport size photos;</li>
<li> 2 copies of a parent’s / legal guardian’s document</li>
<li> Copies of your child’s last 2 school reports for all children transfer to our school;</li>
<li> Registration fee of (non-refundable).</li>
</o>
You can download the Application form in MS Word format/PDF and submit it with all the required documentation.

Upon offer of a place, the school requires a non-refundable deposit of Payable to the cashier of school bank account. The deposit is deductible against the first terms’ fees.

The Certificate must be on official school letterhead and must contain the following information:
- Full name of the child
- Date of enrolment in the school
- Child’s date of birth
- Date the child left the school
- Grade / Class on leaving the school
- School stamp and signature of the Principal
- Curriculum used
