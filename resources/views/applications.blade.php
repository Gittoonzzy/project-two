<h2>Acacia School Admissions</h2>
<p>
Acacia Secondary School admissions policy does not discriminate against any child or their family. All children are welcome to apply to our schools regardless of nationality, ethnicity or religion.

Acacia School does not have provision for children with severe or complex special educational needs. Whenever possible we aim to interview every child and their parents prior to entry.

